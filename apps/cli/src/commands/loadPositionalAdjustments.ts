export async function handleLoadPositionalAdjustments(options: {
  upsert?: boolean;
}): Promise<void> {
  const upsert = Boolean(options?.upsert);
  const opts = getDbOptions();

  console.log(
    `Loading ${POSITIONAL_ADJUSTMENTS.length} positional adjustment seasons (${upsert ? 'upsert' : 'insert'})...`,
  );

  await runWithPublicClient(opts, async (db: PublicDb) => {
    let inserted = 0;
    let updated = 0;
    let skipped = 0;

    for (const row of POSITIONAL_ADJUSTMENTS) {
      const [season, c, firstBase, secondBase, thirdBase, ss, lf, cf, rf, dh] =
        row;

      if (upsert) {
        const result = await db.execute(sql`
          INSERT INTO positional_adjustments (season, c, first_base, second_base, third_base, ss, lf, cf, rf, dh)
          VALUES (${season}, ${c}, ${firstBase}, ${secondBase}, ${thirdBase}, ${ss}, ${lf}, ${cf}, ${rf}, ${dh})
          ON CONFLICT (season)
          DO UPDATE SET
            c = EXCLUDED.c,
            first_base = EXCLUDED.first_base,
            second_base = EXCLUDED.second_base,
            third_base = EXCLUDED.third_base,
            ss = EXCLUDED.ss,
            lf = EXCLUDED.lf,
            cf = EXCLUDED.cf,
            rf = EXCLUDED.rf,
            dh = EXCLUDED.dh
        `);
        const count = Number(result.rowCount ?? 0);
        if (count > 0) {
          updated++;
        }
      } else {
        try {
          await db.execute(sql`
            INSERT INTO positional_adjustments (season, c, first_base, second_base, third_base, ss, lf, cf, rf, dh)
            VALUES (${season}, ${c}, ${firstBase}, ${secondBase}, ${thirdBase}, ${ss}, ${lf}, ${cf}, ${rf}, ${dh})
          `);
          inserted++;
        } catch (err: unknown) {
          const message = err instanceof Error ? err.message : String(err);
          if (message.includes('duplicate key')) {
            skipped++;
          } else {
            throw err;
          }
        }
      }
    }

    if (upsert) {
      console.log(`Done. Upserted ${updated} rows.`);
    } else {
      console.log(
        `Done. Inserted: ${inserted}, Skipped (duplicate): ${skipped}`,
      );
    }
  });
}
