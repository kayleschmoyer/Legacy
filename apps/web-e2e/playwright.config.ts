import { defineConfig, devices } from '@playwright/test';
import path from 'path';

/**
 * Dedicated E2E port — intentionally different from the Vite dev-server (4200)
 * so local test runs exercise the same static-serve path that CI uses.
 */
const E2E_PORT = Number(process.env.E2E_PORT) || 4280;

/**
 * @see https://playwright.dev/docs/test-configuration
 */
export default defineConfig({
  testDir: './src/tests',

  /* Support $env:PLAYWRIGHT_GREP and $env:PLAYWRIGHT_GREP_INVERT so Windows
   * users can pass grep patterns containing | without CMD interpreting the pipe.
   * Example: $env:PLAYWRIGHT_GREP='@critical|@smoke' ; pnpm exec nx e2e web-e2e */
  ...(process.env.PLAYWRIGHT_GREP
    ? { grep: new RegExp(process.env.PLAYWRIGHT_GREP) }
    : {}),
  ...(process.env.PLAYWRIGHT_GREP_INVERT
    ? { grepInvert: new RegExp(process.env.PLAYWRIGHT_GREP_INVERT) }
    : {}),

  /* Authenticate once via global setup, then share storageState with all tests.
   * CI: signs a JWT using JWT_SECRET env var.
   * Local: uses OAuth device flow (opens browser, caches token). */
  globalSetup: require.resolve('./src/global-setup'),
  /* Run tests in files in parallel */
  fullyParallel: true,
  /* Fail the build on CI if you accidentally left test.only in the source code. */
  forbidOnly: !!process.env.CI,
  /* Retry on CI only — 1 retry catches genuine infra blips without tripling runtime */
  retries: process.env.CI ? 1 : 0,
  /* 4 workers: GHA runners have 7GB RAM; Playwright tests are I/O-bound not CPU-bound,
   * so 4 parallel browsers (~400MB) finishes in ~5min vs ~15min at 2 workers */
  workers: process.env.CI ? 4 : undefined,
  /* Per-test timeout cap — prevents a single stuck test from burning 30s (the
   * Playwright default) before failing.  20s leaves headroom for navigation +
   * a few slow assertions while still failing 5-6x faster than the default. */
  timeout: 20000,
  /* Reporter to use. See https://playwright.dev/docs/test-reporters */
  reporter: [
    ['json', { outputFile: 'test-results/results.json' }],
    ['line'], // Console output for real-time feedback
    ...(process.env.CI ? [['blob'] as const] : []),
  ],
  /* Shared settings for all the projects below. See https://playwright.dev/docs/api/class-testoptions. */
  use: {
    /* Base URL to use in actions like `await page.goto('/')`. */
    baseURL: `http://localhost:${E2E_PORT}`,

    /* Pre-authenticated browser state generated by global-setup.ts */
    storageState: path.join(__dirname, '.auth/state.json'),

    /* Cap how long page actions (click, fill, waitFor, goto) can run.
     * Default is 0 (inherits the 20s per-test timeout above, consuming
     * it entirely on a single stuck action).  15s allows one slow navigation
     * while still leaving the test budget for assertions. */
    actionTimeout: 15000,
    navigationTimeout: 15000,

    /* Collect trace when retrying the failed test. See https://playwright.dev/docs/trace-viewer */
    trace: 'on-first-retry',
  },

  /* OS-agnostic snapshot paths — one baseline per browser, no platform suffix.
   * Playwright bundles its own browsers so rendering is near-identical across
   * OSes; sub-pixel font differences are absorbed by maxDiffPixelRatio. */
  snapshotPathTemplate: '{snapshotDir}/{arg}-{projectName}{ext}',

  /* Configure snapshot settings */
  expect: {
    /* Give React 18's non-blocking createRoot().render() time to commit the
     * initial paint + re-render after mocked GraphQL responses arrive.
     * Cold V8 JIT on CI can require 3–4s; 5s gives comfortable headroom. */
    timeout: 5000,
    /* Threshold for visual comparisons */
    toHaveScreenshot: {
      threshold: 0.2,
      maxDiffPixelRatio: 0.01,
      animations: 'disabled',
    },
    /* Maximum difference in pixels for visual comparisons */
    toMatchSnapshot: {
      threshold: 0.2,
    },
  },

  /* Configure projects for major browsers */
  projects: [
    {
      name: 'chromium',
      use: {
        ...devices['Desktop Chrome'],
        viewport: { width: 1280, height: 720 },
      },
    },

    {
      name: 'firefox',
      use: {
        ...devices['Desktop Firefox'],
        viewport: { width: 1280, height: 720 },
      },
    },

    {
      name: 'webkit',
      use: {
        ...devices['Desktop Safari'],
        viewport: { width: 1280, height: 720 },
      },
    },

    /* Test against mobile viewports. */
    {
      name: 'Mobile Chrome',
      use: {
        ...devices['Pixel 5'],
        viewport: { width: 375, height: 667 },
      },
    },
    {
      name: 'Mobile Safari',
      use: {
        ...devices['iPhone 12'],
        viewport: { width: 375, height: 667 },
      },
    },

    /* Test against branded browsers. */
    // {
    //   name: 'Microsoft Edge',
    //   use: { ...devices['Desktop Edge'], channel: 'msedge' },
    // },
    // {
    //   name: 'Google Chrome',
    //   use: { ...devices['Desktop Chrome'], channel: 'chrome' },
    // },
  ],

  /* Serve the static production build — mirrors CI exactly.
   * Run `pnpm exec nx build web` first if dist/apps/web is stale / missing.
   * Uses a dedicated port so the Vite dev-server (4200) can stay running.
   *
   * Best-practice notes (https://playwright.dev/docs/test-webserver):
   *   • cwd pinned to repo root so dist/apps/web resolves regardless of
   *     where `playwright test` is invoked from.
   *   • 127.0.0.1 for the health-check avoids DNS resolution delays.
   *   • stdout/stderr piped so Playwright captures server logs on failure.
   *   • reuseExistingServer only locally — CI always starts a fresh server
   *     so startup failures are caught immediately. */
  webServer: {
    command: `pnpm dlx serve@14.2.4 -s dist/apps/web -l ${E2E_PORT} --no-clipboard`,
    cwd: path.resolve(__dirname, '../..'),
    url: `http://127.0.0.1:${E2E_PORT}`,
    reuseExistingServer: !process.env.CI,
    timeout: 30_000,
    stdout: 'pipe',
    stderr: 'pipe',
  },
});
