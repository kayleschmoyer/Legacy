// Expo config plugin (LS-6402 / LS-7558): materialize apps/app/.env at prebuild
// so the release bundler inlines EXPO_PUBLIC_* values that only live in the
// monorepo root .env.
//
// Why this is needed: `babel-preset-expo` only inlines a `process.env.EXPO_PUBLIC_X`
// read when @expo/env loaded that value, and @expo/env reads .env files from the
// project root (apps/app) — never the monorepo root. There is no apps/app/.env,
// so during Gradle's `expo export:embed` every EXPO_PUBLIC_* read that is only
// defined in the root .env resolves to `undefined` in the release bundle. That is
// the failure class behind LS-6399 (OAuth → localhost) and the stats / websocket /
// rollbar / giphy gaps tracked in LS-6402. app.config.js mutates process.env from
// the root .env, but that mutation does not reliably reach the release transform.
//
// This plugin runs `withDangerousMod` on every prebuild (the documented build-prep
// step — `pnpm prebuild:android`, and the implicit prebuild inside `expo run:*`),
// regenerating apps/app/.env from the root .env + local overrides. The file is
// gitignored and holds only EXPO_PUBLIC_* values; @expo/env loads it natively at
// export:embed time, so dev and release inline an identical set.

const fs = require('fs');
const path = require('path');
const { withDangerousMod } = require('@expo/config-plugins');
const { CONFIG_KEY_ALIASES } = require('./config-aliases');

const GENERATED_HEADER =
  '# AUTO-GENERATED by lib/app-config/plugins/with-expo-public-env.js (LS-7558).\n' +
  '# Regenerated on every `expo prebuild` from the monorepo root .env — do not edit.\n' +
  '# Gitignored; holds the EXPO_PUBLIC_* values @expo/env inlines into the native bundle.\n';

/**
 * Parse a dotenv file into a plain object, or return {} if it does not exist.
 * @param {string} filePath
 * @returns {Record<string, string>}
 */
function parseEnvFile(filePath) {
  if (!fs.existsSync(filePath)) return {};
  return require('dotenv').parse(fs.readFileSync(filePath));
}

/**
 * Serialize an env map to dotenv lines, sorted for deterministic output.
 * @param {Record<string, string>} map
 * @returns {string}
 */
function serializeEnv(map) {
  return Object.keys(map)
    .sort()
    .map((key) => `${key}=${map[key]}`)
    .join('\n');
}

/**
 * Write apps/app/.env from the resolved EXPO_PUBLIC_* set.
 * @param {string} projectRoot - apps/app
 */
function writeExpoPublicEnv(projectRoot) {
  const rootEnv = parseEnvFile(path.resolve(projectRoot, '../../.env'));
  const localEnv = parseEnvFile(path.resolve(projectRoot, '.env.local'));
  // root .env first, local overrides on top, then real process.env (shell / CI /
  // EAS secrets) wins — same precedence app.config.js applies.
  const merged = { ...rootEnv, ...localEnv, ...process.env };

  // Apply CONFIG_KEYS aliases: if the EXPO_PUBLIC_ name is not set but the
  // source (VITE_*) is, copy the value over.
  for (const [target, source] of CONFIG_KEY_ALIASES) {
    if (!merged[target]?.trim() && merged[source]?.trim()) {
      merged[target] = merged[source];
    }
  }

  // Collect all non-empty EXPO_PUBLIC_* entries.
  /** @type {Record<string, string>} */
  const expoPublic = {};
  for (const key of Object.keys(merged)) {
    const value = merged[key];
    if (key.startsWith('EXPO_PUBLIC_') && value != null && value !== '') {
      expoPublic[key] = value;
    }
  }

  fs.writeFileSync(
    path.resolve(projectRoot, '.env'),
    GENERATED_HEADER + serializeEnv(expoPublic) + '\n',
  );
}

/**
 * @param {import('@expo/config-types').ExpoConfig} config
 * @returns {import('@expo/config-types').ExpoConfig}
 */
const withExpoPublicEnv = (config) => {
  // Register on both platforms; the file is platform-agnostic and the write is
  // idempotent, so prebuilding either (or both) platforms keeps it current.
  const mod = (cfg) => {
    writeExpoPublicEnv(cfg.modRequest.projectRoot);
    return cfg;
  };
  let next = withDangerousMod(config, ['android', mod]);
  next = withDangerousMod(next, ['ios', mod]);
  return next;
};

module.exports = withExpoPublicEnv;
module.exports.writeExpoPublicEnv = writeExpoPublicEnv;
