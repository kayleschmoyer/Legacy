import { eq } from 'drizzle-orm';
import type { Database } from 'better-sqlite3';
import {
  cleanupTestData,
  getTestClient,
  getTestDatabase,
  integrationTestSchema,
} from '../../integration-test-setup';
import { getLeague, getUser } from '../__fixtures__';

// Helper function to generate unique invite codes for tests
function generateInviteCode(): string {
  return Math.random().toString(36).substring(2, 10).toUpperCase();
}

describe('League Resolver - Integration Tests', () => {
  let db: ReturnType<typeof getTestDatabase>;
  let client: Database;

  beforeAll(() => {
    db = getTestDatabase();
    client = getTestClient();
  });

  beforeEach(async () => {
    // Clean database before each test
    await cleanupTestData();
  });

  afterEach(async () => {
    // Clean database after each test
    await cleanupTestData();
  });

  describe('getLeagueById', () => {
    it('should query real database and return league', async () => {
      const user = getUser(2); // owner.user@example.com
      const league = getLeague(0); // Test League

      // Create user first (league owner)
      await db
        .insert(integrationTestSchema.users)
        .values({
          id: user.id,
          email: user.email,
          username: user.username,
          accessLevel: user.accessLevel,
        })
        .execute();

      // Insert test data using real database
      const [insertedLeague] = await db
        .insert(integrationTestSchema.leagues)
        .values({
          id: league.id,
          name: league.name,
          owner: user.id,
          inviteCode: league.inviteCode,
          maxRosterSize: league.maxRosterSize,
          minGamesPerSeason: league.minGamesPerSeason,
          gamesPerMatchup: league.gamesPerMatchup,
        })
        .returning();

      // Query using real database
      const [result] = await db
        .select()
        .from(integrationTestSchema.leagues)
        .where(eq(integrationTestSchema.leagues.id, insertedLeague.id))
        .limit(1);

      // Test the result (excluding timestamp - SQLite generates at runtime)
      expect(result).toMatchObject({
        id: league.id,
        name: league.name,
        owner: user.id,
        inviteCode: league.inviteCode,
        maxRosterSize: league.maxRosterSize,
        minGamesPerSeason: league.minGamesPerSeason,
        gamesPerMatchup: league.gamesPerMatchup,
        draftStatus: 'not-started',
        currentMatchup: null,
        // created_at is generated by SQLite and changes each test run
      });
    });

    it('should return null for non-existent league', async () => {
      // Query for non-existent league
      const [result] = await db
        .select()
        .from(integrationTestSchema.leagues)
        .where(eq(integrationTestSchema.leagues.id, 99999))
        .limit(1);

      expect(result).toBeUndefined();
    });

    it('should handle database constraints (unique invite code)', async () => {
      const user = getUser(2); // owner.user@example.com
      const league1 = getLeague(0);
      const league2 = getLeague(1);

      // Create user first
      await db
        .insert(integrationTestSchema.users)
        .values({
          id: user.id,
          email: user.email,
          username: user.username,
          accessLevel: user.accessLevel,
        })
        .execute();

      // First league with specific invite code
      await db
        .insert(integrationTestSchema.leagues)
        .values({
          id: league1.id,
          name: league1.name,
          owner: user.id,
          inviteCode: 'TEST1234',
        })
        .execute();

      // Try to insert second league with same invite code - should throw error
      // Note: We expect SQLite's "UNIQUE constraint failed" error
      try {
        await db
          .insert(integrationTestSchema.leagues)
          .values({
            id: league2.id,
            name: league2.name,
            owner: user.id,
            inviteCode: 'TEST1234', // Duplicate!
          })
          .execute();

        // If we get here, the constraint didn't work
        throw new Error(
          'Expected UNIQUE constraint error but insert succeeded',
        );
      } catch (error) {
        // Verify it's the right kind of error
        expect(error).toBeDefined();
        expect(String(error)).toMatch(/UNIQUE constraint|duplicate key value/i);
      }
    });
  });

  describe('getLeaguesByOwner', () => {
    it('should query multiple leagues for owner', async () => {
      const owner = getUser(2); // owner.user@example.com
      const otherOwner = getUser(1); // admin.user@example.com
      const league1 = getLeague(0); // Test League
      const league2 = getLeague(1); // Second League

      // Create both owners first
      await db
        .insert(integrationTestSchema.users)
        .values([
          {
            id: owner.id,
            email: owner.email,
            username: owner.username,
            accessLevel: owner.accessLevel,
          },
          {
            id: otherOwner.id,
            email: otherOwner.email,
            username: otherOwner.username,
            accessLevel: otherOwner.accessLevel,
          },
        ])
        .execute();

      // Insert multiple leagues with fixture data
      await db.insert(integrationTestSchema.leagues).values([
        {
          id: league1.id,
          name: league1.name,
          owner: owner.id,
          inviteCode: league1.inviteCode,
          maxRosterSize: 25,
          minGamesPerSeason: league1.minGamesPerSeason,
          gamesPerMatchup: league1.gamesPerMatchup,
        },
        {
          id: league2.id,
          name: league2.name,
          owner: owner.id,
          inviteCode: league2.inviteCode,
          maxRosterSize: 30,
          minGamesPerSeason: league2.minGamesPerSeason,
          gamesPerMatchup: league2.gamesPerMatchup,
        },
        {
          id: 999,
          name: 'Other Owner League',
          owner: otherOwner.id,
          inviteCode: 'OTHER123',
          maxRosterSize: 20,
        },
      ]);

      // Query leagues by owner
      const results = await db
        .select()
        .from(integrationTestSchema.leagues)
        .where(eq(integrationTestSchema.leagues.owner, owner.id))
        .orderBy(integrationTestSchema.leagues.id); // Deterministic order

      expect(results).toHaveLength(2);
      expect(
        results.map(
          (l: typeof integrationTestSchema.leagues.$inferSelect) => l.name,
        ),
      ).toEqual([league1.name, league2.name]);

      // Test individual results (excluding timestamps - SQLite generates at runtime)
      results.forEach((result, index) => {
        const expectedLeague = index === 0 ? league1 : league2;
        expect(result).toMatchObject({
          id: expectedLeague.id,
          name: expectedLeague.name,
          owner: owner.id,
          inviteCode: expectedLeague.inviteCode,
          minGamesPerSeason: expectedLeague.minGamesPerSeason,
          gamesPerMatchup: expectedLeague.gamesPerMatchup,
          draftStatus: 'not-started',
          currentMatchup: null,
          // created_at is generated by SQLite and changes each test run
          // maxRosterSize varies (25, 30) - check individually
        });

        const expectedMaxRoster = index === 0 ? 25 : 30;
        expect(result.maxRosterSize).toBe(expectedMaxRoster);
      });
    });

    it('should return empty array for owner with no leagues', async () => {
      const user = getUser(0); // test.user@example.com

      // Create user but no leagues
      await db
        .insert(integrationTestSchema.users)
        .values({
          id: user.id,
          email: user.email,
          username: user.username,
          accessLevel: user.accessLevel,
        })
        .execute();

      const results = await db
        .select()
        .from(integrationTestSchema.leagues)
        .where(eq(integrationTestSchema.leagues.owner, user.id));

      expect(results).toEqual([]);
    });
  });

  describe('createLeague', () => {
    it('should insert league into real database', async () => {
      const user = getUser(2); // owner.user@example.com
      const league = getLeague(0); // Test League

      // Create user first
      await db
        .insert(integrationTestSchema.users)
        .values({
          id: user.id,
          email: user.email,
          username: user.username,
          accessLevel: user.accessLevel,
        })
        .execute();

      const newLeague = {
        id: league.id,
        name: 'Integration Test League',
        owner: user.id,
        inviteCode: 'INTEGR8N',
        maxRosterSize: 40,
        minGamesPerSeason: 15,
        gamesPerMatchup: 7,
      };

      // Insert using real database
      const [inserted] = await db
        .insert(integrationTestSchema.leagues)
        .values(newLeague)
        .returning();

      expect(inserted).toMatchSnapshot();

      // Verify it's actually in the database
      const [queried] = await db
        .select()
        .from(integrationTestSchema.leagues)
        .where(eq(integrationTestSchema.leagues.id, inserted.id));

      expect(queried).toMatchSnapshot();
    });

    it('should generate unique invite codes', async () => {
      const user = getUser(2); // owner.user@example.com

      // Create user first
      await db
        .insert(integrationTestSchema.users)
        .values({
          id: user.id,
          email: user.email,
          username: user.username,
          accessLevel: user.accessLevel,
        })
        .execute();

      const leagueData = {
        name: 'Test League',
        owner: user.id,
      };

      // Insert multiple leagues with unique invite codes
      const leagues = await Promise.all([
        db
          .insert(integrationTestSchema.leagues)
          .values({ ...leagueData, inviteCode: generateInviteCode() })
          .returning(),
        db
          .insert(integrationTestSchema.leagues)
          .values({ ...leagueData, inviteCode: generateInviteCode() })
          .returning(),
        db
          .insert(integrationTestSchema.leagues)
          .values({ ...leagueData, inviteCode: generateInviteCode() })
          .returning(),
      ]);

      // Extract invite codes from returned arrays
      const inviteCodes = leagues.map(
        (leagueArray) => leagueArray[0].inviteCode,
      );

      // All should be unique
      const uniqueCodes = new Set(inviteCodes);
      expect(uniqueCodes.size).toBe(3);
    });

    it('should apply default values', async () => {
      const user = getUser(2); // owner.user@example.com
      const league = getLeague(0); // Test League

      // Create user first
      await db
        .insert(integrationTestSchema.users)
        .values({
          id: user.id,
          email: user.email,
          username: user.username,
          accessLevel: user.accessLevel,
        })
        .execute();

      // Insert minimal league (only required fields)
      const [inserted] = await db
        .insert(integrationTestSchema.leagues)
        .values({
          id: league.id,
          name: 'Minimal League',
          owner: user.id,
          inviteCode: 'MINIMAL1',
        })
        .returning();

      // Check defaults are applied with snapshot
      expect(inserted).toMatchSnapshot();
      expect(inserted.maxRosterSize).toBe(25); // Default from schema
      expect(inserted.minGamesPerSeason).toBe(10); // Default from schema
      expect(inserted.gamesPerMatchup).toBe(5); // Default from schema
      expect(inserted.draftStatus).toBe('not-started'); // Default from schema
    });
  });

  describe('deleteLeague', () => {
    it('should delete league from real database', async () => {
      const user = getUser(2); // owner.user@example.com
      const league = getLeague(0); // Test League

      // Create user first
      await db
        .insert(integrationTestSchema.users)
        .values({
          id: user.id,
          email: user.email,
          username: user.username,
          accessLevel: user.accessLevel,
        })
        .execute();

      // Insert league
      const [inserted] = await db
        .insert(integrationTestSchema.leagues)
        .values({
          id: league.id,
          name: 'To Be Deleted',
          owner: user.id,
          inviteCode: 'DELETE01',
        })
        .returning();

      // Verify it exists
      const [beforeDelete] = await db
        .select()
        .from(integrationTestSchema.leagues)
        .where(eq(integrationTestSchema.leagues.id, inserted.id));
      expect(beforeDelete).toMatchSnapshot();

      // Delete it
      await db
        .delete(integrationTestSchema.leagues)
        .where(eq(integrationTestSchema.leagues.id, inserted.id));

      // Verify it's gone
      const [afterDelete] = await db
        .select()
        .from(integrationTestSchema.leagues)
        .where(eq(integrationTestSchema.leagues.id, inserted.id));
      expect(afterDelete).toBeUndefined();
    });

    it('should handle cascade deletes with teams', async () => {
      const user = getUser(2); // owner.user@example.com
      const league = getLeague(0); // Test League

      // Create user first
      await db
        .insert(integrationTestSchema.users)
        .values({
          id: user.id,
          email: user.email,
          username: user.username,
          accessLevel: user.accessLevel,
        })
        .execute();

      // Insert league
      const [insertedLeague] = await db
        .insert(integrationTestSchema.leagues)
        .values({
          id: league.id,
          name: 'League with Team',
          owner: user.id,
          inviteCode: 'CASCADE1',
        })
        .returning();

      // Insert team
      const [team] = await db
        .insert(integrationTestSchema.teams)
        .values({
          name: 'Test Team',
          leagueId: insertedLeague.id,
        })
        .returning();

      // Verify team exists
      const [teamBefore] = await db
        .select()
        .from(integrationTestSchema.teams)
        .where(eq(integrationTestSchema.teams.id, team.id));
      expect(teamBefore).toMatchSnapshot();

      // Delete league
      await db
        .delete(integrationTestSchema.leagues)
        .where(eq(integrationTestSchema.leagues.id, insertedLeague.id));

      // Verify cascade delete worked (team should be deleted)
      const [teamAfter] = await db
        .select()
        .from(integrationTestSchema.teams)
        .where(eq(integrationTestSchema.teams.id, team.id));
      expect(teamAfter).toBeUndefined();
    });
  });

  describe('Performance', () => {
    it('should handle bulk inserts efficiently', async () => {
      // Create 10 users for valid owner foreign keys (10 users x 10 leagues each = 100 total)
      const users = Array.from({ length: 10 }, (_, i) => ({
        id: 100 + i,
        email: `bulk-user-${i}@example.com`,
        username: `bulkuser${i}`,
        accessLevel: 'user' as const,
      }));

      await db.insert(integrationTestSchema.users).values(users).execute();

      const startTime = Date.now();

      // Bulk insert 100 leagues with valid owner IDs
      const values = Array.from({ length: 100 }, (_, i) => ({
        name: `League ${i}`,
        owner: 100 + Math.floor(i / 10), // Map to created user IDs (10 leagues per owner)
        inviteCode: generateInviteCode(),
        maxRosterSize: 25 + i,
      }));

      await db.insert(integrationTestSchema.leagues).values(values);

      const endTime = Date.now();
      const duration = endTime - startTime;

      // Verify all inserted
      const count = await db.select().from(integrationTestSchema.leagues);
      expect(count).toHaveLength(100);

      // Performance check (should be fast with in-memory SQLite)
      expect(duration).toBeLessThan(1000); // Less than 1 second

      console.log(`✅ Bulk insert of 100 leagues took ${duration}ms`);
    });
  });
});
