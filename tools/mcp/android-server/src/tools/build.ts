import { existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import process from 'node:process';
import { jsonResult, minifiedJson, truncate } from '../format.js';
import { runCommand } from '../run-command.js';
import { resolveGradlew } from '../android-env.js';
import type { ToolResult } from '../types.js';

export interface BuildParams {
  variant?: 'debug' | 'release';
  arch?: string;
  versionCode?: number;
}

// Android ABI names, comma-separated (e.g. "x86_64" or "arm64-v8a,x86_64" —
// see apps/app/android/gradle.properties). `arch` is interpolated into a
// `-P` Gradle property and, on Windows, `runCommand` invokes gradlew.bat
// with `shell: true` — cmd.exe builds one command line from argv there, so
// an unvalidated value could inject shell syntax (LS-8815 review finding).
export const ARCH_LIST = /^[A-Za-z0-9_,-]+$/;

const BUILD_TIMEOUT_MS = 600_000; // Gradle assemble, not a quick call
// Generous cap (not the 4000-char default elsewhere) — Gradle failures often
// need the full stack trace/error block, which can run long; showOmitted
// keeps the cut visible instead of silently dropping context.
const OUTPUT_CHAR_LIMIT = 16_000;

export function capitalize(s: string): string {
  return s.charAt(0).toUpperCase() + s.slice(1);
}

export async function androidBuild(params: BuildParams): Promise<ToolResult> {
  if (params.arch !== undefined && !ARCH_LIST.test(params.arch)) {
    return jsonResult(
      {
        error: `Invalid arch "${params.arch}": must match ${ARCH_LIST} (letters, digits, '-', '_', ',' only).`,
      },
      true,
    );
  }

  const variant = params.variant ?? 'debug';
  const { gradlew, needsShell } = resolveGradlew();

  if (!existsSync(gradlew)) {
    return jsonResult(
      {
        error: `gradlew not found at ${gradlew}. Run \`pnpm install\` first — apps/app/android is generated by the Expo prebuild step.`,
      },
      true,
    );
  }

  const androidDir = dirname(gradlew);
  const task = `app:assemble${capitalize(variant)}`;
  const args = [task];
  if (params.arch) args.push(`-PreactNativeArchitectures=${params.arch}`);

  // versionCode: apps/app/android/app/build.gradle prefers GITHUB_RUN_NUMBER
  // (falling back to a semver-derived value). A local build re-installing
  // over a device that already has a CI build hits
  // INSTALL_FAILED_VERSION_DOWNGRADE unless it gets its own monotonically
  // increasing code — default to the current epoch second when the caller
  // doesn't already have one set (mirrors the ticket's called-out gotcha).
  const env = {
    GITHUB_RUN_NUMBER:
      params.versionCode !== undefined
        ? String(params.versionCode)
        : (process.env.GITHUB_RUN_NUMBER ??
          String(Math.floor(Date.now() / 1000))),
  };

  try {
    const output = await runCommand(
      gradlew,
      args,
      androidDir,
      BUILD_TIMEOUT_MS,
      needsShell,
      10 * 1024 * 1024,
      env,
    );
    const apkPath = join(
      androidDir,
      'app',
      'build',
      'outputs',
      'apk',
      variant,
      `app-${variant}.apk`,
    );
    return {
      content: [
        {
          type: 'text',
          text: minifiedJson({
            ok: true,
            variant,
            apkPath: existsSync(apkPath) ? apkPath : null,
            output: truncate(output, OUTPUT_CHAR_LIMIT, { showOmitted: true }),
          }),
        },
      ],
    };
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    return jsonResult(
      { error: truncate(message, OUTPUT_CHAR_LIMIT, { showOmitted: true }) },
      true,
    );
  }
}
